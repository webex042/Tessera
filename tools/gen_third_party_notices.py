"""Generate THIRD_PARTY_NOTICES.md from local data only (no network).

    cargo deny --offline list -f json -l crate > deny-list.json
    (cd ui && pnpm licenses list --json --prod > pnpm-lic.json)
    python tools/gen_third_party_notices.py deny-list.json pnpm-lic.json > THIRD_PARTY_NOTICES.md

Lists every Rust crate in the build graph and every production UI package with its licence(s),
plus the pinned binaries and model files the app uses (tools/sidecar.lock, tools/models.lock).
Full licence texts ship in the installer (Stage 10); this file is the inventory.
"""
import json
import sys
from collections import defaultdict
from pathlib import Path

root = Path(__file__).resolve().parent.parent
deny = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
pnpm = json.loads(Path(sys.argv[2]).read_text(encoding="utf-8"))

ours = {"tessara", "tsr-core", "tsr-win", "tsr-store", "tsr-retrieval", "tsr-guard", "tsr-infer", "tsr-capture",
        "tsr-net", "tsr-pipeline", "tsr-draft", "tsr-evals", "uia-probe"}
by_license = defaultdict(list)
for key, v in deny.items():
    name, version = key.split(" ")[:2]
    if name in ours:
        continue
    lic = " OR ".join(v.get("licenses", [])) or "UNKNOWN"
    by_license[lic].append(f"{name} {version}")

out = ["# Third-party notices", "",
       "Generated by `tools/gen_third_party_notices.py` from `cargo deny list` and `pnpm licenses list`",
       "(offline). Licence expressions are as declared by each package. Full texts ship with the installer.", ""]

out += ["## Binaries and data the app runs or loads", "",
        "| component | version | licence | source |", "|---|---|---|---|",
        "| llama.cpp (`llama-server`, ggml) | b11900 | MIT | github.com/ggml-org/llama.cpp (pinned in `tools/sidecar.lock`) |",
        "| ONNX Runtime | 1.31.0 | MIT | github.com/microsoft/onnxruntime (pinned in `tools/sidecar.lock`) |",
        "| Qwen3-VL-4B-Instruct GGUF (Q4_K_M, mmproj F16) | — | Apache-2.0 | Qwen (pinned in `tools/models.lock`); downloaded only with the user's approval |",
        "| Microsoft Edge WebView2 Runtime | system | Microsoft software licence | installed with Windows / by the WebView2 bootstrapper |",
        ""]

out += ["## Rust crates", "", f"{sum(len(v) for v in by_license.values())} crates.", ""]
for lic in sorted(by_license):
    out.append(f"### {lic}")
    out.append("")
    out.append(", ".join(sorted(by_license[lic], key=str.lower)))
    out.append("")

out += ["## UI packages (production)", ""]
for lic in sorted(pnpm):
    names = sorted(f"{p['name']} {', '.join(p['versions'])}" for p in pnpm[lic])
    out.append(f"### {lic}")
    out.append("")
    out.append(", ".join(names))
    out.append("")

sys.stdout.reconfigure(encoding="utf-8", newline="\n")
print("\n".join(out))
